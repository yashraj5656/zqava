
"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import "../dashboard/creator.css";

export default function CreatorRegisterPage() {
  const [loading, setLoading] = useState(false);
  const [message, setMessage] = useState("");
  const router = useRouter();

  async function apply() {
    setLoading(true);
    setMessage("");

    try {
      const response = await fetch("/api/creator/register", {
        method: "POST",
      });

      const data = await response.json();

      if (response.ok || response.status === 409) {
        router.push("/creator/dashboard");
        return;
      }

      setMessage(data.message || "Unable to submit your application.");
    } catch {
      setMessage("Something went wrong. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <main className="creator-page">
      <section className="creator-panel">
        <p className="creator-eyebrow">ZQAVA PARTNER PROGRAM</p>
        <h1>Become a ZQAVA Creator</h1>
        <p className="creator-description">
          Share ZQAVA with your audience, bring in new users,
          and earn commission from eligible platform profit
          generated by your referrals.
        </p>

        <div className="creator-benefits">
          <div>
            <strong>25%</strong>
            <span>Commission rate</span>
          </div>
          <div>
            <strong>12 months</strong>
            <span>Eligible earning period per referred customer</span>
          </div>
          <div>
            <strong>One link</strong>
            <span>Track registrations from your referrals</span>
          </div>
        </div>

        <p className="creator-note">
          Applications are reviewed before referral links become active.
          Commission applies to eligible platform contribution profit,
          not the full booking value. Earnings are subject to verification
          and the program terms.
        </p>

        {message && <p className="creator-message">{message}</p>}

        <button
          className="creator-button"
          onClick={apply}
          disabled={loading}
          type="button"
        >
          {loading ? "Submitting..." : "Apply to become a creator"}
        </button>
      </section>
    </main>
  );
}
